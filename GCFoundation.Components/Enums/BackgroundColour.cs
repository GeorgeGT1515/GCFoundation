namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Defines the available background colours for components.
    /// </summary>
    public enum BackgroundColour
    {
        /// <summary>
        /// 	Main dark background colour. Use with a text shade of 100 or lighter (like --gcds-text-light).
        /// </summary>
        dark,

        /// <summary>
        /// Light background colour (alternative to white). Use with a text shade of 700 or darker (like --gcds-text-primary).
        /// </summary>
        light,

        /// <summary>
        /// Highlight background colour. Use with a text shade of 100 or lighter (like --gcds-text-light).
        /// </summary>
        primary,

        /// <summary>
        /// Main background colour. Use with a text shade of 700 or darker (like --gcds-text-primary).
        /// </summary>
        white
    }
}
