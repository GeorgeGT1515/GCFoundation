namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Defines the sort direction for a table column.
    /// </summary>
    public enum SortDirection
    {
        /// <summary>
        /// Indicates no default sort order.
        /// </summary>
        none,

        /// <summary>
        /// Indicates ascending sort order.
        /// </summary>
        asc,

        /// <summary>
        /// Indicates descending sort order.
        /// </summary>
        desc
    }
}