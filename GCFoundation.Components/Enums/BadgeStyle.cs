namespace GCFoundation.Components.Enums
{
    /// <summary>
    /// Enumerates available badge styles (colour variations).
    /// </summary>
    public enum BadgeStyle
    {
        /// <summary>
        /// Use the primary theme colour.
        /// </summary>
        primary,

        /// <summary>
        /// Use the secondary theme colour.
        /// </summary>
        secondary,

        /// <summary>
        /// Success state (typically green).
        /// </summary>
        success,

        /// <summary>
        /// Danger or error state (typically red).
        /// </summary>
        danger,

        /// <summary>
        /// Informational message (typically blue).
        /// </summary>
        info,

        /// <summary>
        /// Warning state (typically yellow).
        /// </summary>
        warning,

        /// <summary>
        /// Light/neutral background.
        /// </summary>
        light,

        /// <summary>
        /// Dark/contrasting background.
        /// </summary>
        dark
    }
}